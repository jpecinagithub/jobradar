import { SOURCE_QUALITY, type Job } from './types';

export const DEMO_MODE = true;

/** ISO string for "n days ago" (negative n = in the future). */
const daysAgo = (n: number): string => new Date(Date.now() - n * 864e5).toISOString();

const normalizeTitle = (t: string): string =>
  t.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();

/* A seed carries the fields we author by hand; makeJob() fills
   every remaining Job field with sensible demo defaults. */
type JobSeed = Partial<Job> & {
  id: string;
  title: string;
  company: string;
  description: string;
  responsibilities: string[];
  requirements: string[];
  skills: string[];
  source: string;
  sourceUrl: string;
  applyUrl: string;
};

function makeJob(seed: JobSeed): Job {
  const sourceType = seed.sourceType ?? 'PRIMARY';
  const salaryGiven = seed.salaryMin != null || seed.salaryMax != null;
  return {
    companySize: 'enterprise',
    remoteType: 'on_site',
    employmentType: 'permanent',
    seniority: 'mid',
    salaryConfidence: salaryGiven ? 'CONFIRMED' : 'UNKNOWN',
    languagesRequired: ['English'],
    languagesPreferred: [],
    languageConfidence: 'CONFIRMED',
    industry: ['Technology'],
    function: ['IT'],
    visaSponsorship: 'not_mentioned',
    relocation: false,
    relocationConfidence: 'UNKNOWN',
    expatriatePackage: false,
    status: 'ACTIVE',
    postedAt: seed.postedAt ?? daysAgo(5),
    discoveredAt: seed.discoveredAt ?? seed.postedAt ?? daysAgo(5),
    lastVerifiedAt: seed.lastVerifiedAt ?? daysAgo(0),
    ...seed,
    // derived fields are re-asserted after the spread
    normalizedTitle: normalizeTitle(seed.title),
    sourceType,
    qualityScore: SOURCE_QUALITY[sourceType],
  };
}

